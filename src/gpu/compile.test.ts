import { describe, expect, it } from "vitest";
import { type FieldSpecArg, listFieldFns } from "../nodes/fieldJson.js";
import { compileFieldSpec, supportedGpuFieldFns } from "./index.js";
import type { FieldKernelLayout } from "./index.js";

const LAYOUT: FieldKernelLayout = {
  attributes: {
    P: { type: "f32", tupleSize: 3 },
    density: { type: "f32", tupleSize: 1 },
    uv: { type: "f32", tupleSize: 2 },
    active: { type: "bool", tupleSize: 1 },
    id: { type: "u32", tupleSize: 1 },
    material: { type: "i32", tupleSize: 1 },
  },
};

function count(haystack: string, needle: string): number {
  return haystack.split(needle).length - 1;
}

describe("compileFieldSpec goldens", () => {
  it("constant scalar kernel", () => {
    const k = compileFieldSpec({ fn: "constant", value: 2 }, LAYOUT);
    expect(k.wgsl).toBe(`// Generated by pcg-ts compileFieldSpec (WGSL field kernel).
// Dispatch: 1D, chunked; each chunk runs ceil(chunkElements / 64) workgroups of 64
// with element index i = chunkOffset + gid.x; one invocation per element.

struct PcgParams {
  count: u32,
  seed: u32,
  chunkOffset: u32,
}

@group(0) @binding(0) var<uniform> params: PcgParams;
@group(0) @binding(1) var<storage, read_write> outBuf: array<f32>;

@compute @workgroup_size(64)
fn main(@builtin(global_invocation_id) gid: vec3<u32>) {
  let i = gid.x + params.chunkOffset;
  if (i >= params.count) {
    return;
  }
  let v0 = 2f;
  outBuf[i] = v0;
}
`);
    expect(k.entryPoint).toBe("main");
    expect(k.workgroupSize).toBe(64);
    expect(k.outType).toBe("f32");
    expect(k.outTupleSize).toBe(1);
    expect(k.inputs).toEqual([]);
    expect(k.bindings).toEqual({ uniforms: 0, output: 1 });
    expect(k.usesSeed).toBe(false);
  });

  it("attribute * randomField kernel (hash library, seed uniform)", () => {
    const k = compileFieldSpec(
      { fn: "mul", args: [{ fn: "attribute", name: "density" }, { fn: "randomField", key: "jitter" }] },
      LAYOUT,
    );
    expect(k.wgsl).toBe(`// Generated by pcg-ts compileFieldSpec (WGSL field kernel).
// Dispatch: 1D, chunked; each chunk runs ceil(chunkElements / 64) workgroups of 64
// with element index i = chunkOffset + gid.x; one invocation per element.

struct PcgParams {
  count: u32,
  seed: u32,
  chunkOffset: u32,
}

@group(0) @binding(0) var<uniform> params: PcgParams;
@group(0) @binding(1) var<storage, read> in0: array<f32>; // attribute "P": f32 tupleSize 3
@group(0) @binding(2) var<storage, read> in1: array<f32>; // attribute "density": f32 tupleSize 1
@group(0) @binding(3) var<storage, read_write> outBuf: array<f32>;

fn pcg_hash_mix(h_in: u32, value: u32) -> u32 {
  var k = value * 0xcc9e2d51u;
  k = (k << 15u) | (k >> 17u);
  k = k * 0x1b873593u;
  var h = h_in ^ k;
  h = (h << 13u) | (h >> 19u);
  h = h * 5u + 0xe6546b64u;
  return h;
}

fn pcg_hash_finalize(h_in: u32) -> u32 {
  var h = h_in ^ (h_in >> 16u);
  h = h * 0x85ebca6bu;
  h = h ^ (h >> 13u);
  h = h * 0xc2b2ae35u;
  h = h ^ (h >> 16u);
  return h;
}

fn pcg_hash3(a: u32, b: u32, c: u32) -> u32 {
  return pcg_hash_finalize(pcg_hash_mix(pcg_hash_mix(pcg_hash_mix(0x0ff426f8u, a), b), c));
}

fn pcg_hash4(a: u32, b: u32, c: u32, d: u32) -> u32 {
  return pcg_hash_finalize(pcg_hash_mix(pcg_hash_mix(pcg_hash_mix(pcg_hash_mix(0x89985015u, a), b), c), d));
}

fn pcg_hash_float(h: u32) -> f32 {
  return f32(h >> 8u) * 5.960464477539063e-8f;
}

@compute @workgroup_size(64)
fn main(@builtin(global_invocation_id) gid: vec3<u32>) {
  let i = gid.x + params.chunkOffset;
  if (i >= params.count) {
    return;
  }
  let v0 = in1[i];
  let v1 = pcg_hash_float(pcg_hash3(params.seed, 0x02049853u, pcg_hash4(bitcast<u32>(in0[i * 3u]), bitcast<u32>(in0[i * 3u + 1u]), bitcast<u32>(in0[i * 3u + 2u]), 0u)));
  let v2 = v0 * v1;
  outBuf[i] = v2;
}
`);
    expect(k.usesSeed).toBe(true);
    // P rides along even though the spec never names it: randomField keys
    // on point identity, so it reads the position bits (and the `seed`
    // attribute, which this layout does not carry, so it folds in 0u).
    expect(k.inputs).toEqual([
      { name: "P", type: "f32", tupleSize: 3, binding: 1 },
      { name: "density", type: "f32", tupleSize: 1, binding: 2 },
    ]);
    expect(k.bindings).toEqual({ uniforms: 0, output: 3 });
  });

  it("ramp over length(position) kernel (per-instance helper)", () => {
    const k = compileFieldSpec(
      {
        fn: "ramp",
        args: [{ fn: "length", args: [{ fn: "position" }] }],
        stops: [
          [0, 1],
          [2, 0.5],
          [4, 0],
        ],
      },
      LAYOUT,
    );
    expect(k.wgsl).toBe(`// Generated by pcg-ts compileFieldSpec (WGSL field kernel).
// Dispatch: 1D, chunked; each chunk runs ceil(chunkElements / 64) workgroups of 64
// with element index i = chunkOffset + gid.x; one invocation per element.

struct PcgParams {
  count: u32,
  seed: u32,
  chunkOffset: u32,
}

@group(0) @binding(0) var<uniform> params: PcgParams;
@group(0) @binding(1) var<storage, read> in0: array<f32>; // attribute "P": f32 tupleSize 3
@group(0) @binding(2) var<storage, read_write> outBuf: array<f32>;

fn pcg_ramp_0(t: f32) -> f32 {
  if (t <= 0f) {
    return 1f;
  }
  if (t >= 4f) {
    return 0f;
  }
  if (t <= 2f) {
    return 1f + -0.5f * ((t - 0f) / 2f);
  }
  return 0.5f + -0.5f * ((t - 2f) / 2f);
}

@compute @workgroup_size(64)
fn main(@builtin(global_invocation_id) gid: vec3<u32>) {
  let i = gid.x + params.chunkOffset;
  if (i >= params.count) {
    return;
  }
  let v0 = vec3<f32>(in0[i * 3u], in0[i * 3u + 1u], in0[i * 3u + 2u]);
  let v1 = dot(v0, v0);
  let v2 = sqrt(v1);
  let v3 = pcg_ramp_0(v2);
  outBuf[i] = v3;
}
`);
  });
});

