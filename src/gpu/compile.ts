// attribute access

function describeLayout(layout: FieldKernelLayout): string {
  const names = Object.keys(layout.attributes).sort();
  if (names.length === 0) return "the layout declares no attributes";
  return `layout attributes: ${names.map((n) => JSON.stringify(n)).join(", ")}`;
}

/**
 * Validate an attribute reference against the layout. `origin` prefixes
 * the message for indirect reads (`position` reads `P`).
 */
function resolveLayoutAttr(
  ctx: CompileCtx,
  path: string,
  name: string,
  expectTupleSize: number | undefined,
  origin: string,
): FieldKernelAttr {
  const attrs = ctx.layout.attributes;
  if (!Object.hasOwn(attrs, name)) {
    throw new GpuCompileError(
      `${path}: ${origin}attribute ${JSON.stringify(name)} is not in the kernel layout; ${describeLayout(ctx.layout)}`,
    );
  }
  const attr = attrs[name];
  if (attr.type === "string") {
    throw new GpuCompileError(
      `${path}: ${origin}attribute ${JSON.stringify(name)} has type "string"; a string column has ` +
        "no numeric value to read — test it with " +
        `{ fn: "attributeIs", name: ${JSON.stringify(name)}, value: "..." }, which is 1 where it ` +
        "matches and 0 elsewhere, or read a numeric or bool attribute",
    );
  }
  if (expectTupleSize !== undefined && attr.tupleSize !== expectTupleSize) {
    throw new GpuCompileError(
      `${path}: ${origin}attribute ${JSON.stringify(name)}: expected tupleSize ${expectTupleSize}, ` +
        `got ${attr.tupleSize} in the kernel layout`,
    );
  }
  if (attr.tupleSize > 4) {
    throw tupleError(path, `${origin}attribute ${JSON.stringify(name)}`, attr.tupleSize);
  }
  return attr;
}

/**
 * Load an attribute as an f32 expression value (i32/u32/bool lanes are
 * converted with `f32(...)`, mirroring the CPU number/bool→f32 read).
 */
function loadAttribute(
  ctx: CompileCtx,
  path: string,
  name: string,
  expectTupleSize: number | undefined,
  origin: string,
): Val {
  const attr = resolveLayoutAttr(ctx, path, name, expectTupleSize, origin);
  const b = ctx.binding(name);
  const ts = attr.tupleSize;
  const conv = (e: string): string => (attr.type === "f32" ? e : `f32(${e})`);
  if (ts === 1) return ctx.emit(conv(`${b.varName}[i]`), 1);
  const lanes: string[] = [];
  for (let k = 0; k < ts; k++) {
    lanes.push(conv(`${b.varName}[${flatIndex(ts, k)}]`));
  }
  return ctx.emit(`vec${ts}<f32>(${lanes.join(", ")})`, ts);
}

function flatIndex(ts: number, k: number): string {
  if (ts === 1) return "i";
  return k === 0 ? `i * ${ts}u` : `i * ${ts}u + ${k}u`;
}

// ---------------------------------------------------------------------------
// handlers

type Handler = (spec: Record<string, unknown>, path: string, ctx: CompileCtx) => Val;

const HANDLERS = new Map<string, Handler>();

/** Field fns the WGSL compiler supports, sorted (derived from its handler table). */
export function supportedGpuFieldFns(): string[] {
  return [...HANDLERS.keys()].sort();
}

function compileNode(spec: Record<string, unknown>, path: string, ctx: CompileCtx): Val {
  const fn = String(spec.fn);
  const handler = HANDLERS.get(fn);
  if (!handler) {
    throw new GpuCompileError(
      `${path}: field fn "${fn}" is not supported by the WGSL compiler; ` +
        `supported fns: ${supportedGpuFieldFns().join(", ")}`,
    );
  }
  return handler(spec, path, ctx);
}

function compileArg(v: unknown, path: string, ctx: CompileCtx): Val {
  if (typeof v === "number") return ctx.emit(wgslF32(v, path), 1);
  if (Array.isArray(v)) return compileConstantTuple(v as number[], path, ctx);
  return compileNode(v as Record<string, unknown>, path, ctx);
}

function compileConstantTuple(values: readonly number[], path: string, ctx: CompileCtx): Val {
  const ts = values.length;
  if (ts > 4) throw tupleError(path, "constant", ts);
  if (ts === 1) return ctx.emit(wgslF32(values[0], path), 1);
  const lits = values.map((v) => wgslF32(v, path));
  return ctx.emit(`vec${ts}<f32>(${lits.join(", ")})`, ts);
}

function specArgs(spec: Record<string, unknown>): unknown[] {
  return spec.args as unknown[];
}

// -- inputs -----------------------------------------------------------------

HANDLERS.set("constant", (spec, path, ctx) => {
  const v = spec.value;
  if (typeof v === "number") return ctx.emit(wgslF32(v, `${path}.value`), 1);
  return compileConstantTuple(v as number[], `${path}.value`, ctx);
});

HANDLERS.set("attribute", (spec, path, ctx) => {
  const name = spec.name as string;
  const expect = spec.tupleSize as number | undefined;
  return loadAttribute(ctx, path, name, expect, "");
});

/**
 * Validate the STRING column `attributeIs` tests. Deliberately not
 * `resolveLayoutAttr`, which refuses strings wholesale and is right to:
 * a string column has no numeric value, so `attribute("species")` has
 * nothing to read. This one reads no value either — it compares an index
 * against an index — so the refusal it needs is the mirror image, and a
 * NUMERIC column is the mistake here. The message names `eq` for the
 * same reason the CPU constructor does: absence of a value is data,
 * absence of the right KIND of attribute is a bug the author can fix.
 *
 * No tuple cap, unlike the numeric path: only component 0 is read, so a
 * wide string tuple costs nothing and never has to fit in a `vecN`.
 */
function resolveStringAttr(ctx: CompileCtx, path: string, name: string): FieldKernelAttr {
  const attrs = ctx.layout.attributes;
  if (!Object.hasOwn(attrs, name)) {
    throw new GpuCompileError(
      `${path}: attributeIs: attribute ${JSON.stringify(name)} is not in the kernel layout; ${describeLayout(ctx.layout)}`,
    );
  }
  const attr = attrs[name];
  if (attr.type !== "string") {
    throw new GpuCompileError(
      `${path}: attributeIs: attribute ${JSON.stringify(name)} has type ${JSON.stringify(attr.type)}, ` +
        "but attributeIs tests a string attribute; compare a numeric attribute with " +
        `{ fn: "eq", args: [{ fn: "attribute", name: ${JSON.stringify(name)} }, <number>] }`,
    );
  }
  return attr;
}

// The literal rides a UNIFORM SLOT and is never baked, and unlike `param`
// — where the uniform is the better of two workable lowerings — here it
// is the only sound one. What the kernel needs is the literal's index in
// THIS geometry's string table, and that index is a property of the
// geometry rather than of the spec: the table is insertion-ordered and
// rebuilt by clone, filter and merge, so two cells of one world hold
// "pine" at different indices. The kernel cache key is spec text plus
// each attribute's name/type/tupleSize (`evaluator.ts`) and carries no
// table contents, so a baked index would be shared by two geometries
// that disagree about it — the cache would serve the wrong constant, and
// silently, which is the failure this whole design exists to prevent.
// Riding a uniform makes the kernel table-agnostic: one kernel, one
// index resolved per dispatch against the geometry in hand.
//
// Component 0 of a possibly-tuple column, matching `Attribute.getString`'s
// default and so the CPU `attributeIs`; the stride is applied for the
// same reason every other read applies it.
//
// -1 for an absent literal (filled by `constSlotValues`) needs no special
// case here: no table index equals it, so the comparison is false on
// every lane and the column is the zeros the CPU produces — `f32(u32)`
// is non-negative for every bit pattern, garbage included.
//
// The comparison is f32 where the CPU's is integer, which is exact up to
// 2^24 — the same bound the module doc records for `index`, and reached
// here only by a string table holding more than 16.7 million DISTINCT
// values on one attribute. Past it two indices could round together and
// the device would match an element the CPU does not. Recorded rather
// than guarded because the uniform tail is f32 for every slot kind and
// the case is unreachable in any geometry the library can build.
HANDLERS.set("attributeIs", (spec, path, ctx) => {
  const name = spec.name as string;
  const value = spec.value as string;
  const attr = resolveStringAttr(ctx, path, name);
  const b = ctx.binding(name);
  const slot = ctx.attrIsSlot(name, value);
  return ctx.emit(
    `select(0f, 1f, f32(${b.varName}[${flatIndex(attr.tupleSize, 0)}]) == params.consts[${slot}].x)`,
    1,
  );
});

HANDLERS.set("position", (_spec, path, ctx) => {
  return loadAttribute(ctx, path, "P", 3, "position reads ");
});

// A named value lowers to a UNIFORM SLOT, never to a literal — forced
// rather than chosen. `compileFieldSpec` is handed a spec and never
// values, so a literal lowering has nowhere to read from; and the uniform
// is the path this runtime already settled on next door, where a constant
// apply param "contributes its tuple size and slot — never its values, so
// a constant edit rebinds the uniform and reuses the pipeline"
// (applyKernels.ts). Two further properties fall out of that: it costs no
// storage buffer (`collectAttrNames` finds nothing in a `param`, which is
// the whole saving against carrying the value in an attribute column),
// and it is BIT-EXACT against the CPU — better than a literal, since a
// WGSL front end may flush a `-0` or subnormal literal to `+0` but never
// a uniform load (see run.ts).
//
// The arity comes from the binding recorded on this spec node, not from
// the value: it decides the emitted text, so it is in the specialization
// key, while the value is not. An unbound param compiles as a scalar —
// nothing will ever dispatch it (the evaluator declines, so the CPU
// raises the actionable refusal), but it must still COMPILE, because the
// key and the kernel are exactly what a compiler needs from an unbound
// reference.
//
// A FIELD binding lowers the other way, and has to: it is not one value
// but an expression, so it is COMPILED IN PLACE, exactly as if the author
// had written it here. That costs no uniform slot and no storage buffer
// of its own — whatever attributes it reads are already in the pre-pass,
// which walks into it (`collectAttrNames`) — and it fuses into the same
// kernel rather than adding a dispatch, which is the improvement over the
// per-point attribute column this route replaces. The value-free kernel
// key rebuilds it for the same reason (`specKernelKey`): a spliced field
// decides the emitted text, so it belongs to the kernel's identity, where
// a spliced number deliberately does not.
HANDLERS.set("param", (spec, path, ctx) => {
  const name = spec.name as string;
  const bound = paramSpecOf(spec as unknown as FieldSpec);
  if (bound !== undefined) {
    return compileNode(bound as unknown as Record<string, unknown>, `${path}<${name}>`, ctx);
  }
  const { slot, arity } = ctx.paramSlot(name);
  const read = (k: number): string => `params.consts[${slot}].${XYZW[k]}`;
  if (arity === 1) return ctx.emit(read(0), 1);
  return ctx.emit(`vec${arity}<f32>(${Array.from({ length: arity }, (_v, k) => read(k)).join(", ")})`, arity);
});

HANDLERS.set("index", (_spec, _path, ctx) => ctx.emit("f32(i)", 1));

// Normalized index: i / (count - 1), the closed [0, 1] span. `max(count,
// 2u) - 1u` is the CPU's `n > 1 ? n - 1 : 1` written without a branch —
// at count 1 the lone lane divides by 1 and reads 0, exactly as the CPU
// does, and the divisor can never be 0. (Count 0 dispatches nothing on
// either side.)
HANDLERS.set("fraction", (_spec, _path, ctx) =>
  ctx.emit("f32(i) / f32(max(params.count, 2u) - 1u)", 1),
);

// The node seed is already a uniform (`params.seed`, written per
// dispatch), so this leaf costs no binding, no const slot, and — the
// part that matters — nothing in `kernel.key`, which is a function of
// the SPEC. One kernel serves every seed the graph is ever given, where
// a baked literal would have specialized a pipeline per seed into an
// unbounded cache: the two-keys hazard `param` documented, arriving here
// as a value that changes on every drag of the seed box.
//
// Split rather than `f32(params.seed)`. The CPU column is an f32, so
// the value both sides must agree on is the nearest f32 to a full u32,
// and a u32 past 2^24 is exactly the case where converting it whole is
// LOSSY — which for a hashed node seed is not an edge case but every
// value. Rather than depend on how a given adapter rounds that
// conversion, the pieces are made exact and the rounding is left to one
// correctly-rounded add: `seed >> 8` is under 2^24 and converts
// exactly, `* 256.0` only moves the exponent, and the sum is
// `Math.fround(seed)`. Measured both ways on the reference adapter
// (RTX 5090, D3D12) — it agrees either way, which is the point: this
// spelling does not need it to.
HANDLERS.set("nodeSeed", (_spec, _path, ctx) => {
  ctx.usesSeed = true;
  return ctx.emit("f32(params.seed >> 8u) * 256.0 + f32(params.seed & 0xFFu)", 1);
});

// randomField is keyed on POINT IDENTITY on the CPU (see
// `src/data/identity.ts`): the f32 bit patterns of P.xyz hashed with the
// `seed` attribute, then folded into (params.seed, key). A layout carries
// no domain, so a spec compiled against one without P — vertex, primitive
// or detail, where the CPU falls back to the element index — throws here
// and resolves on the CPU instead of inventing a key the CPU never used.
HANDLERS.set("randomField", (spec, path, ctx) => {
  const key = spec.key;
  const keyHash = typeof key === "string" ? hashString(key) : ((key as number | undefined) ?? 0) >>> 0;
  ctx.usesSeed = true;
  ctx.libRoots.add("pcg_hash3");
  ctx.libRoots.add("pcg_hash4");
  ctx.libRoots.add("pcg_hash_float");
  const origin = "randomField's per-point identity reads ";
  const P = resolveLayoutAttr(ctx, path, "P", undefined, origin);
  if (P.tupleSize < 3) {
    throw new GpuCompileError(
      `${path}: ${origin}attribute "P" with x, y and z (tupleSize 3), got tupleSize ${P.tupleSize}`,
    );
  }
  const pVar = ctx.binding("P").varName;
  // Bits, never the value: hashCombine truncates a float toward zero, so
  // every position inside the unit cube would key identically.
  const bits = (k: number): string => {
    const e = `${pVar}[${flatIndex(P.tupleSize, k)}]`;
    return P.type === "f32" ? `bitcast<u32>(${e})` : `bitcast<u32>(f32(${e}))`;
  };
  // A missing `seed` column contributes 0, exactly as a column of
  // defaults would — the CPU makes the same substitution.
  let seedExpr = "0u";
  const seedAttr = Object.hasOwn(ctx.layout.attributes, "seed")
    ? ctx.layout.attributes.seed
    : undefined;
  if (seedAttr !== undefined) {
    if (seedAttr.tupleSize !== 1 || (seedAttr.type !== "u32" && seedAttr.type !== "i32")) {
      throw new GpuCompileError(
        `${path}: ${origin}the standard point attribute "seed" as a u32 or i32 scalar, but the ` +
          `layout has it as ${seedAttr.type}x${seedAttr.tupleSize}; this field resolves on the CPU instead`,
      );
    }
    const sVar = ctx.binding("seed").varName;
    seedExpr = seedAttr.type === "u32" ? `${sVar}[i]` : `bitcast<u32>(${sVar}[i])`;
  }
  const ident = `pcg_hash4(${bits(0)}, ${bits(1)}, ${bits(2)}, ${seedExpr})`;
  return ctx.emit(`pcg_hash_float(pcg_hash3(params.seed, ${wgslHexU32(keyHash)}, ${ident}))`, 1);
});

// -- elementwise combinators ------------------------------------------------

/**
 * Register an elementwise combinator: children broadcast per the scalar
 * rule and the template receives size-matched operand references.
 */
function registerElementwise(name: string, arity: number, template: (refs: string[], size: number) => string): void {
  HANDLERS.set(name, (spec, path, ctx) => {
    const args = specArgs(spec);
    const vals: Val[] = [];
    for (let i = 0; i < arity; i++) {
      vals.push(compileArg(args[i], `${path}.args[${i}]`, ctx));
    }
    const size = broadcastSizes(name, path, vals.map((v) => v.size));
    const refs = vals.map((v) => splat(v, size));
    return ctx.emit(template(refs, size), size);
  });
}

